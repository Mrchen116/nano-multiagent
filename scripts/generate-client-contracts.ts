const outputs: ReadonlyArray<readonly [string, string]> = [
  [SWIFT_OUT, renderSwift()],
  [RUST_OUT, renderRust()],
];

const checkOnly = process.argv.includes('--check');
for (const [targetPath, expected] of outputs) {
  if (checkOnly) {
    let actual = '';
    try {
      actual = await readFile(targetPath, 'utf8');
    } catch {
      throw new Error(
        `Missing generated client contract ${targetPath}. Run pnpm exec tsx scripts/generate-client-contracts.ts`,
      );
    }
    if (actual !== expected) {
      throw new Error(
        `Stale generated client contract ${targetPath}. Run pnpm exec tsx scripts/generate-client-contracts.ts`,
      );
    }
  } else {
    await mkdir(dirname(targetPath), { recursive: true });
    await writeFile(targetPath, expected, 'utf8');
  }
}
