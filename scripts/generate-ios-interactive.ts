import { build } from 'esbuild';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { createRequire } from 'node:module';

const root = resolve(import.meta.dirname, '..');
const output = resolve(root, 'src/IM/ios/NanoIM/Resources/InteractiveRuntime.js');
const result = await build({entryPoints:[resolve(root, 'src/IM/ios/Runtime/interactive-runtime.ts')], bundle:true, write:false,
  format:'iife', globalName:'NanoInteractive', platform:'neutral', target:'es2020', minify:true,
  banner:{js:'// Generated by scripts/generate-ios-interactive.ts. OpenUI lang-core 1.0.1 and Zod 4.6.5; MIT licenses in InteractiveRuntime-LICENSE.txt.'}});
const text = result.outputFiles[0].text;
const require = createRequire(import.meta.url);
const core = dirname(dirname(require.resolve('@openuidev/lang-core')));
const licenses = [
  ['@openuidev/lang-core 1.0.1', resolve(core, 'LICENSE')],
  ['Zod 4.6.5', resolve(dirname(require.resolve('zod/package.json')), 'LICENSE')],
  ['ci-info (bundled optional telemetry dependency; no networking host is provided)', resolve(dirname(createRequire(resolve(core,'package.json')).resolve('ci-info/package.json')), 'LICENSE')],
];
const notices = (await Promise.all(licenses.map(async ([name,path]) => `${name}\n${await readFile(path,'utf8')}`))).join('\n\n');
for (const [path, content] of [[output,text],[resolve(dirname(output),'InteractiveRuntime-LICENSE.txt'),notices]]) {
  if (process.argv.includes('--check')) {
    if (await readFile(path, 'utf8') !== content) throw new Error(`Stale iOS interactive resource ${path}. Run pnpm exec tsx scripts/generate-ios-interactive.ts`);
  } else { await mkdir(dirname(path), {recursive:true}); await writeFile(path, content); }
}
